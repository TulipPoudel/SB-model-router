import sys
from pathlib import Path
import pandas as pd
import yaml

ROOT = Path(__file__).resolve().parents[1]
CSV = ROOT / "data" / "GA_debate_speech_dataset_20260129.csv"
SESSION = 79

# Slot number = file number: first country -> UN_01 -> un_01.txt
COUNTRIES = ["Nauru", "Australia", "Guyana", "Jamaica", "New Zealand",
             "Singapore", "Malta", "Ghana", "Kenya", "United Arab Emirates"]

LICENSE = ("UN copyright; non-commercial use with attribution. Source list: "
           "UN Dag Hammarskjold Library, General debate speeches dataset v3 (Jan 2026). "
           "https://www.un.org/en/about-us/terms-of-use")

df = pd.read_csv(CSV)
df = df[df["GA Session"] == SESSION]
df = df[df["Agenda Items"].astype(str).str.contains("GENERAL DEBATE")]
df = df.drop_duplicates("Member State")

rows = []
for c in COUNTRIES:
    match = df[df["Member State"] == c]
    if match.empty:
        sys.exit(f"Country not found in CSV: {c}")
    rows.append(match.iloc[0])

sources = []
for i, r in enumerate(rows):
    sid = f"UN_{i + 1:02d}"
    sources.append({
        "source_id": sid,
        "symbol": r["Meeting Symbol"],
        "title": f"General Debate statement - {r['Member State']} (79th session)",
        "url": r["UNDL Link"],
        "local_file": f"data/public_sources/raw/{sid.lower()}.txt",
        "date": r["Meeting Date"],
        "speaker": r["Name"],
        "country_or_org": r["Member State"],
        "license_notes": LICENSE,
        "max_words": 700,
        "key_facts": [],
        "fields": {},
    })

(ROOT / "data" / "public_sources" / "raw").mkdir(parents=True, exist_ok=True)
header = "# Generated by scripts/pick_un_sources.py. Fill key_facts and fields for each source.\n"
(ROOT / "data" / "public_sources_manifest.yaml").write_text(
    header + yaml.safe_dump({"sources": sources}, sort_keys=False, allow_unicode=True),
    encoding="utf-8",
)
print(pd.DataFrame(rows)[["Meeting Symbol", "Meeting Date", "Name", "Member State", "UNDL Link"]].to_string())